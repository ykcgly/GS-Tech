// ★ 去抖：一次右键可能连发两个事件（Slimefun 的主手/副手各一个），
//   只认第一次 ⇒ 不然「按一下」会被当成「按两下」（开了又立刻关）
function sgDebounced(p) {
    try {
        if (SG_DEBOUNCE_MS <= 0) return false;
        var uuid = '' + p.getUniqueId();
        var v = SG_TOUCH[uuid];
        var now = sgNow();
        if (v != null && (0 + v) + SG_DEBOUNCE_MS > now) return true;
        SG_TOUCH[uuid] = now;
        return false;
    } catch (e) { return false; }
}

