// ★★ 转朝向：`setRotation` 管的是 yRot + yHeadRot，Paper 的 `setBodyYaw` 管 yBodyRot。
//    人形生物（村民 / 卫道士）渲染时**躯干**用的是 yBodyRot ⇒ **两个都要设**；
//    只设 setRotation 会变成「身体不动、只有脑袋在转」。
function scFace(ent, yaw) {
    try { ent.setRotation(yaw, 0.0); } catch (e) { }
    try { ent.setBodyYaw(yaw); } catch (e) { }
}

// ★ 「原地」保险：被玩家砍中会被**击退**（速度是服务端给的，和 AI 无关），
//   一旦挪窝就不再是「原地转圈」了 ⇒ 每刻把速度清零，
//   真被推开了就**传送回锚点**（只在被推开时才传，免得每刻发包把转圈搞卡顿）。
//   ★★ 第六十一批：加了「起飞」之后，**竖直方向也得跟** ——
//      锚点每刻都在往上走，而 AI 是关掉的（怪自己不会跟上去），
//      只判水平的话会出现「锚点飞上天、怪还杵在地面」。
//      ★ 平飞阶段 dy ≈ 0，所以还是"只在被推开时才传"，不会白白发包。
function scPin(ent, anchor, yaw) {
    try {
        try { var z = scVec(0.0, 0.0, 0.0); if (z != null) ent.setVelocity(z); } catch (e) { }
        var cur = null;
        try { cur = ent.getLocation(); } catch (e) { cur = null; }
        if (cur == null || anchor == null) return;
        var dx = cur.getX() - anchor.getX();
        var dz = cur.getZ() - anchor.getZ();
        var dy = cur.getY() - anchor.getY();
        if (dx * dx + dz * dz <= 0.02 && Math.abs(dy) <= 0.02) return;   // 没被推开 / 没落后 ⇒ 不动它
        try { anchor.setYaw(yaw); anchor.setPitch(0.0); } catch (e) { }
        try { ent.teleport(anchor); } catch (e) { }
    } catch (e) { }
}

// ★★ 第六十一批：算出「这一刻该往上抬几格」
//   · 16 秒前 ⇒ 0 ｜ 16~22 秒 ⇒ 0 → 8 ｜ 22 秒后 ⇒ 固定 8
//   ★★ 为什么用 smoothstep（s = t²(3−2t)）而不是线性：
//      线性的话**起步和到顶都是"啪"地一顿**（速度从 0 突然变成满速、又突然归零）。
//      smoothstep 在 t=0 和 t=1 处**导数都是 0** ⇒ 两头慢、中间快，
//      读起来就是"缓缓离地 → 加速 → 稳稳停在空中"，正是用户要的「要有过程」。
function scFlyLift(uuid) {
    try {
        var m = SG_MOB[uuid];
        if (m == null || m.t0 == null) return 0.0;
        var el = sgNow() - m.t0;
        if (!(el > SC_FLY_START_MS)) return 0.0;          // ★ 写成 !(a>b) ⇒ NaN 也走这条
        if (el >= SC_FLY_END_MS) return SC_FLY_HEIGHT;    // ★ 到顶就停住
        var t = (el - SC_FLY_START_MS) / (SC_FLY_END_MS - SC_FLY_START_MS);
        return SC_FLY_HEIGHT * t * t * (3.0 - 2.0 * t);
    } catch (e) { return 0.0; }
}

