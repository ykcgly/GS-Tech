// 召唤一对（起播时调）
function scSpawnPair(p) {
    try {
        var uuid = '' + p.getUniqueId();
        scClear(uuid);
        var loc = null;
        try { loc = p.getLocation(); } catch (e) { loc = null; }
        if (loc == null) return;
        var w = null;
        try { w = loc.getWorld(); } catch (e) { w = null; }
        if (w == null) return;

        var yaw = 0.0;
        try { yaw = loc.getYaw(); } catch (e) { yaw = 0.0; }

        // ★ 「右边一格」= 玩家右手方向的水平分量。
        //   游戏里 yaw = 0 朝 +Z（南），此时右手边是 −X（西）
        //   ⇒ 右向量 = (−cos(yaw), −sin(yaw))
        var rad = yaw * Math.PI / 180.0;
        var rx = -Math.cos(rad), rz = -Math.sin(rad);

        var vLoc = loc.clone();
        var dLoc = loc.clone();
        try { dLoc.add(rx * SC_RIGHT, 0.0, rz * SC_RIGHT); } catch (e) { }

        var v = scSpawnOne(w, vLoc, 'VILLAGER');
        var d = scSpawnOne(w, dLoc, 'VINDICATOR');
        if (v != null) scSetup(v, SC_VILLAGER_NAME, yaw);
        if (d != null) { scSetup(d, SC_VINDICATOR_NAME, yaw); scBareHands(d); }

        // ★★ 第六十一批：起飞要按**歌的时间**走，所以基准取「起播时刻」。
        //   sgPlayStart 里是**先**写 SG_PLAY 再调 scSpawnPair ⇒ 这里读得到。
        //   （拿不到就退到当前时刻，两者其实只差几微秒。）
        var t0 = sgNow();
        try {
            var stp = SG_PLAY[uuid];
            if (stp != null && stp.start != null) t0 = stp.start;
        } catch (e) { }

        SG_MOB[uuid] = { v: v, d: d, va: yaw, da: yaw, vl: vLoc, dl: dLoc, n: 0,
                         t0: t0, vy0: vLoc.getY(), dy0: dLoc.getY() };
    } catch (e) { }
}

// ★ 每刻一次：转圈 + 拽回原地 + 补血（由播放链每刻调一次）
function scSpin(uuid) {
    try {
        var m = SG_MOB[uuid];
        if (m == null) return;
        // ★★ 第六十一批：先按时间算出该抬多高，把**两只的锚点**一起抬高。
        //   ★ 只抬锚点、不直接搬实体 —— 因为锚点是"唯一真相"：
        //       scPin（拽回原位）和 scFx（粒子取两只中点）读的都是锚点，
        //       锚点一升，拽回和粒子就**自动**跟着上天，不用在两处各写一遍。
        //   ★ 用 vy0 + 抬升量 **重算**（不是在旧值上累加）⇒ 丢刻 / 卡顿都不会漂。
        var lift = scFlyLift(uuid);
        if (m.vl != null) { try { m.vl.setY(m.vy0 + lift); } catch (e) { } }
        if (m.dl != null) { try { m.dl.setY(m.dy0 + lift); } catch (e) { } }
        // ★ 一个往左、一个往右
        m.va = scNorm(m.va + SC_SPIN_DEG);
        m.da = scNorm(m.da - SC_SPIN_DEG);
        if (scAlive(m.v)) { scFace(m.v, m.va); scPin(m.v, m.vl, m.va); scKeepAlive(m.v); }
        if (scAlive(m.d)) { scFace(m.d, m.da); scPin(m.d, m.dl, m.da); scKeepAlive(m.d); }
    } catch (e) { }
}

// ★ 每刻一次：在**两只正中间**撒战斗粒子（一直撒到音乐结束）
function scFx(uuid) {
    try {
        if (!SC_FX) return;
        var m = SG_MOB[uuid];
        if (m == null || m.vl == null || m.dl == null) return;
        var w = null;
        try { w = m.vl.getWorld(); } catch (e) { w = null; }
        if (w == null) return;

        // 正中间：水平取中点，高度取胸口（脚下 + 1.0）
        var mx = (m.vl.getX() + m.dl.getX()) / 2.0;
        var my = (m.vl.getY() + m.dl.getY()) / 2.0 + 1.0;
        var mz = (m.vl.getZ() + m.dl.getZ()) / 2.0;

        var P = null;
        try { P = Java.type('org.bukkit.Particle'); } catch (e) { P = null; }
        if (P == null) return;

        var nk = SC_FX_KINDS.length;
        for (var k = 0; k < SC_FX_PER_TICK; k++) {
            m.n = (m.n + 1) % nk;
            var pt = null;
            try { pt = P[SC_FX_KINDS[m.n]]; } catch (e) { pt = null; }
            if (pt == null) continue;
            var pl = scLoc(w,
                mx + (Math.random() - 0.5) * 0.8,
                my + (Math.random() - 0.5) * 0.9,
                mz + (Math.random() - 0.5) * 0.8);
            if (pl == null) continue;
            // ★★ `World.spawnParticle` 在 1.21.11 里有 **18 个重载** ⇒ 和第五十四批
            //    「排任务失败」是同一类坑（GraalJS 分不清重载）。
            //    6 参 `(Particle, Location, int, double, double, double)` 按参数个数
            //    是**唯一**的，正常能选中；万一抛错就退到 8 参的「纯 double」版。
            try { w.spawnParticle(pt, pl, 1, 0.0, 0.0, 0.0); }
            catch (e1) {
                try {
                    w.spawnParticle(pt, pl.getX(), pl.getY(), pl.getZ(), 1, 0.0, 0.0, 0.0);
                } catch (e2) { }
            }
        }
    } catch (e) { }
}

// ★ 保险：脚本被重载（/rsc reload）时，旧实例的播放链断在半路 ⇒ 那两只就没人管了。
//   这里按记分板标签把残留的清掉，只在**第一次右键**时做一次
//   （那时世界肯定已经加载好了，脚本加载时还不一定）。
function scPurge() {
    if (SC_PURGED) return;
    SC_PURGED = true;
    try {
        var worlds = null;
        try { worlds = getServer().getWorlds(); } catch (e) { worlds = null; }
        if (worlds == null) return;
        var nw = 0;
        try { nw = worlds.size(); } catch (e) { nw = 0; }
        for (var i = 0; i < nw; i++) {
            var w = null;
            try { w = worlds.get(i); } catch (e) { w = null; }
            if (w == null) continue;
            var list = null;
            try { list = w.getEntities(); } catch (e) { list = null; }
            if (list == null) continue;
            var n = 0;
            try { n = list.size(); } catch (e) { n = 0; }
            for (var j = 0; j < n; j++) {
                var ent = null;
                try { ent = list.get(j); } catch (e) { ent = null; }
                if (ent == null) continue;
                var hit = false;
                try { hit = ent.getScoreboardTags().contains(SC_TAG); } catch (e) { hit = false; }
                if (hit) { try { ent.remove(); } catch (e) { } }
            }
        }
    } catch (e) { }
}


// ==========================================================
//  播放引擎
// ----------------------------------------------------------
//  ★ 为什么不用「给每个音符排一个 runTaskLater」：
//    本曲有 1202 个音符，那样要排 1202 个任务；而且 runTaskLater 的延迟是
//    **按刻算的**（1 刻 = 50ms），本曲 1 个 NBS tick = 140.25ms ⇒ 会越播越偏。
//  ★ 这里的做法：**每刻一步的自调度链**，用系统毫秒减去起播时刻，
//    把「到点了还没放」的音符一次性全放掉 ⇒ **不会累积漂移**；
//    服务器卡一下也只是把攒下的音符一起补放，不会越拖越乱。
//
//  ★★★ 第五十四批修正（用户实测：日志说『排任务失败』、右键完全没声音）：
//    **不要用 getServer().getScheduler().runTaskTimer(plugin, jsFunction, 1, 1)**。
//    原因是 BukkitScheduler 上同时挂着两个重载：
//        runTaskTimer(Plugin, Runnable,            long, long) : BukkitTask
//        runTaskTimer(Plugin, Consumer<BukkitTask>, long, long) : void
//    GraalJS 拿一个 JS 函数去选，**分不清该转成哪一个** ⇒ 抛异常。
//    ⇒ 改用**本附属其它 13 处心跳一直在用**的 RSC 注入函数 `runLater(fn, delay)`
//      （它内部把 fn 固定成 java.util.function.Function，没有重载歧义）。
//  ★ `runLater` 排出去的任务**拿不到句柄、cancel 不掉**（本附属技能库里记着这条），
//    所以停播靠**世代号**：链上每一步先看自己的 gen 还等不等于表里的 gen，
//    不等就**不再排下一步** ⇒ 链自己断掉。
//  ★★ 世代号用**只增不减的全局计数器 SG_GEN**，绝不复位 ——
//    若按「表里旧值 +1」算，停掉再开很容易又得到同一个号，
//    旧链在途的那一步就会**认成自己还活着** ⇒ 两条链同时播（声音重叠、还停不掉）。
// ==========================================================
var SG_PLAY = {};     // uuid -> { p, start, i, gen }
var SG_GEN  = 0;      // ★ 全局单调递增的世代号（永不复位）

// 拿插件实例（只在 runLater 不可用的退路里才用得到）
function sgPlugin() {
    try {
        var pm = getServer().getPluginManager();
        var pl = null;
        try { pl = pm.getPlugin('RykenSlimeCustomizer'); } catch (e) { pl = null; }
        if (pl == null) {
            try { pl = Java.type('org.lins.mmmjjkx.rykenslimefuncustomizer.RykenSlimefunCustomizer').INSTANCE; }
            catch (e) { }
        }
        if (pl == null) { try { pl = pm.getPlugin('Slimefun'); } catch (e) { } }
        return pl;
    } catch (e) { return null; }
}

// 停掉某个玩家正在播的歌（把世代号作废，链上在途的那一步会自终止）
function sgPlayStopUuid(uuid) {
    try {
        scClear(uuid);           // ★ 生物和歌一起收（放在最前，下面早退也不会漏）
        var st = SG_PLAY[uuid];
        if (st == null) return;
        st.gen = 0;              // 0 永远不等于任何真实世代号 ⇒ 旧链必断
        SG_PLAY[uuid] = null;
    } catch (e) { }
}

// 排一步（delay 刻之后执行 fn）。
//  ★★ 三条路依次试，**第一条是正路**，后面两条只是「别整个哑掉」的保险。
function sgSchedule(fn, delay) {
    // ① 正路：RSC 注入的 runLater（本附属 13 处心跳都在用，实测可用）
    try { runLater(fn, delay); return true; } catch (eRL) { }

    // ② 退路一：用 GraalJS 的 Java.extend **显式**造一个 Runnable。
    //    直接传 JS 函数给 runTaskLater 会撞上 Runnable/Consumer 重载歧义，
    //    显式造出 Runnable 就没有歧义了。
    try {
        var RC = Java.type('java.lang.Runnable');
        var Impl = Java.extend(RC, { run: function () { fn(); } });
        var rr = new Impl();
        var sched = getServer().getScheduler();
        var pl = sgPlugin();
        if (sched != null && pl != null) { sched.runTaskLater(pl, rr, delay); return true; }
    } catch (e1) { }

    // ③ 退路二：直接传函数（多半会因重载歧义失败，但试一下不要钱）
    try {
        var sched = getServer().getScheduler();
        var pl = sgPlugin();
        if (sched != null && pl != null) { sched.runTaskLater(pl, fn, delay); return true; }
    } catch (e2) {
        try { getServer().getLogger().warning('[构思技艺] 咒术回战 排任务失败: ' + e2); } catch (e3) { }
    }
    return false;
}

// 自调度链：每刻一步。被停掉（gen 变了）/ 退服 / 播完 ⇒ 断链
function sgPlayLoop(uuid, gen) {
    sgSchedule(function () {
        var st = null;
        try { st = SG_PLAY[uuid]; } catch (e0) { st = null; }
        if (st == null || st.gen !== gen) return;      // ★ 已被停掉 / 取代 ⇒ 断链
        var p = st.p;
        var ok = true;
        try { if (p == null || !p.isOnline()) ok = false; } catch (e1) { ok = false; }
        if (!ok) { sgPlayStopUuid(uuid); return; }      // 退服 ⇒ 收尾并断链
        scSpin(uuid);                                   // ★ 转圈 + 拽回原地 + 补血
        scFx(uuid);                                     // ★ 两只中间的战斗粒子
        sgPlayPulse(uuid);
        var st2 = null;
        try { st2 = SG_PLAY[uuid]; } catch (e2) { st2 = null; }
        if (st2 != null && st2.gen === gen) sgPlayLoop(uuid, gen);   // 没播完 ⇒ 排下一步
    }, 1);
}

// 起播（先把上一首停掉）
function sgPlayStart(p) {
    try {
        var uuid = '' + p.getUniqueId();
        sgPlayStopUuid(uuid);

        SG_GEN = SG_GEN + 1;                           // ★ 只增不减，绝不复位
        var gen = SG_GEN;
        SG_PLAY[uuid] = { p: p, start: sgNow(), i: 0, gen: gen };
        scSpawnPair(p);                                // ★ 召唤「宿瘫」与「五条舞」
        sgPlayLoop(uuid, gen);
        return true;
    } catch (e) {
        try { getServer().getLogger().warning('[构思技艺] 咒术回战 起播失败: ' + e); } catch (e2) { }
        return false;
    }
}

// 心跳：把「到点了」的音符全放掉（由 sgPlayLoop 每刻调一次）
function sgPlayPulse(uuid) {
    try {
        var st = SG_PLAY[uuid];
        if (st == null) return;                    // 已经被停掉了
        var p = st.p;
        if (p == null || !p.isOnline()) { sgPlayStopUuid(uuid); return; }   // 退服了

        var el  = sgNow() - st.start;              // 已经播了多少毫秒
        var loc = null;
        while (st.i < SG_N && SG_TL[st.i * 3] <= el) {
            var code = SG_TL[st.i * 3 + 1];
            var snd  = SG_SND[(code / 32) | 0];    // 高位 = 音效下标
            var vol  = SG_TL[st.i * 3 + 2];        // 0~100
            st.i++;
            if (snd == null) continue;

            var v = SG_VOL * (vol / 100);
            var g = SG_GAIN[snd];
            if (g != null) v = v * g;
            if (v <= 0) continue;

            if (loc == null) loc = p.getLocation();   // 跟着玩家走
            var pit = SG_PITCH[code % 32];
            try {
                if (SG_OWNER_ONLY) p.playSound(loc, snd, v, pit);
                else               p.getWorld().playSound(loc, snd, v, pit);
            } catch (e) { }
        }
        if (st.i >= SG_N) sgPlayStopUuid(uuid);    // 播完了
    } catch (e) { }
}

