function onButtonGroupClick(p, slot, clickedItem, clickAction, mode) {
    try {
        if (p == null) return;
        if (GG_Material == null || GG_ItemStack == null) return;

        // ---------- 构造一本写好内容的成书 ----------
        var st = new GG_ItemStack(GG_Material.WRITTEN_BOOK, 1);
        var meta = null;
        try { meta = st.getItemMeta(); } catch (e) { meta = null; }
        if (meta == null) return;

        try { meta.setTitle(GG_TITLE); } catch (e) { }
        try { meta.setAuthor(GG_AUTHOR); } catch (e) { }

        if (GG_ArrayList != null) {
            try {
                var pages = new GG_ArrayList();
                for (var i = 0; i < GG_PAGES.length; i++) pages.add(GG_PAGES[i]);
                meta.setPages(pages);
            } catch (e) { }
        }

        try { st.setItemMeta(meta); } catch (e) { }

        // ---------- 发放 ----------
        p.getInventory().addItem(st);

        // ★ 2026-10-09 第十批：按需求删除「你收下了 构思技艺图鉴，右键即可翻阅」这句聊天提示
        try { p.playSound(p.getLocation(), 'item.book.page_turn', 1.0, 1.2); } catch (e) { }
    } catch (err) {
        try { sendMessage(p, '&c图鉴发放出错: ' + err); } catch (e) { }
        try { getServer().getLogger().warning('[构思技艺] 图鉴 onButtonGroupClick 出错: ' + err); } catch (e) { }
    }
}
